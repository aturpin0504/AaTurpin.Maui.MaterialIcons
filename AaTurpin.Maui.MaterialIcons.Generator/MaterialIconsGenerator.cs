using System;
using System.Collections.Generic;
using System.IO;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace AaTurpin.Maui.MaterialIcons.Generator;

/// <summary>
/// Incremental Roslyn Source Generator that reads <c>MaterialIcons-Regular.codepoints</c>
/// at compile time and generates all 2,235 <c>public const string</c> fields on <c>Icons</c>.
/// </summary>
[Generator(LanguageNames.CSharp)]
public sealed class MaterialIconsGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        // 1. Filter AdditionalFiles for any file ending in ".codepoints"
        IncrementalValuesProvider<AdditionalText> codepointsFiles = context.AdditionalTextsProvider
            .Where(static (AdditionalText file) => file.Path.EndsWith(".codepoints", StringComparison.OrdinalIgnoreCase));

        // 2. Read the text content of the .codepoints file
        IncrementalValuesProvider<string?> codepointsContents = codepointsFiles
            .Select(static (AdditionalText file, CancellationToken cancellationToken) => file.GetText(cancellationToken)?.ToString());

        // 3. Generate Icons.g.cs whenever the .codepoints content changes
        context.RegisterSourceOutput(codepointsContents, static (spc, content) =>
        {
            if (string.IsNullOrWhiteSpace(content))
                return;

            var sb = new StringBuilder(262_144);
            sb.AppendLine("// <auto-generated/>");
            sb.AppendLine("#nullable enable");
            sb.AppendLine();
            sb.AppendLine("namespace AaTurpin.Maui.MaterialIcons;");
            sb.AppendLine();
            sb.AppendLine("public static partial class Icons");
            sb.AppendLine("{");

            var seenNames = new HashSet<string>(StringComparer.Ordinal);
            using var reader = new StringReader(content);
            string? line;

            while ((line = reader.ReadLine()) != null)
            {
                if (string.IsNullOrWhiteSpace(line))
                    continue;

                // Each line in MaterialIcons-Regular.codepoints has the format:
                // <snake_case_icon_name> <hex_codepoint>
                // Example: account_balance_wallet e850
                int spaceIndex = line.IndexOf(' ');
                if (spaceIndex <= 0)
                    continue;

                string rawName = line.Substring(0, spaceIndex).Trim();
                string hexCode = line.Substring(spaceIndex + 1).Trim();
                if (rawName.Length == 0 || hexCode.Length == 0)
                    continue;

                string identifier = ToPascalCaseIdentifier(rawName);
                if (!seenNames.Add(identifier))
                    continue;

                sb.Append("    /// <summary>Material Icon <c>")
                  .Append(rawName)
                  .Append("</c> (<c>\\u")
                  .Append(hexCode)
                  .AppendLine("</c>).</summary>");

                sb.Append("    public const string ")
                  .Append(identifier)
                  .Append(" = \"\\u")
                  .Append(hexCode)
                  .AppendLine("\";");
                sb.AppendLine();
            }

            sb.AppendLine("}");

            spc.AddSource("Icons.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        });
    }

    /// <summary>
    /// Converts a snake_case Material Icon name (e.g. <c>account_balance_wallet</c> or <c>10k</c>)
    /// into a valid C# PascalCase identifier (<c>AccountBalanceWallet</c> or <c>_10k</c>).
    /// </summary>
    private static string ToPascalCaseIdentifier(string snakeCase)
    {
        string[] parts = snakeCase.Split(new[] { '_' }, StringSplitOptions.RemoveEmptyEntries);
        var sb = new StringBuilder(snakeCase.Length + 2);

        foreach (string part in parts)
        {
            sb.Append(char.ToUpperInvariant(part[0]));
            if (part.Length > 1)
                sb.Append(part.Substring(1));
        }

        // C# identifiers cannot begin with a digit (e.g., "10k" -> "_10k", "3d_rotation" -> "_3dRotation")
        if (sb.Length > 0 && char.IsDigit(sb[0]))
            sb.Insert(0, '_');

        // Escape C# reserved keywords if any exist (e.g., "class" -> "Class", which is already uppercase)
        return sb.ToString();
    }
}
